/**
 * Derives a plausible star distribution from a product's average rating and
 * review count. Real storefronts show all reviews; this mock has a written
 * subset, so the histogram is synthesised rather than stored.
 */
export function ratingDistribution(avg: number, count: number): number[] {
  const five = Math.min(count, Math.max(1, Math.round(count * (avg >= 4.6 ? 0.78 : avg >= 4.3 ? 0.62 : 0.45))));
  const four = Math.min(count - five, Math.max(1, Math.round(count * 0.22)));
  const three = Math.min(count - five - four, Math.round(count * 0.06));
  const two = Math.min(count - five - four - three, Math.round(count * 0.02));
  const one = Math.max(0, count - five - four - three - two);
  return [one, two, three, four, five];
}